async function runAttendanceSnapshotTests() {
    let passed=0;
    const $=id=>document.getElementById(id);
    const assert=(condition,label)=>{if(!condition)throw Error(label);passed++;};
    const value=index=>$('kpis').children[index].querySelector('strong').textContent;
    const change=(id,value)=>{$(id).value=value;$(id).dispatchEvent(new Event('change',{bubbles:true}));};
    $('reset').click();
    assert(value(0)==='57.1%','Attendance must be four validated shifts divided by seven expected, not late-without-punch');
    assert(value(1)==='7'&&value(2)==='5','Expected shifts exclude leave; clock-in evidence includes pending validation');
    assert(value(3)==='1'&&value(4)==='2','Late arrivals require a matching clock-in; missing includes absent');
    assert(value(5)==='1'&&value(6)==='1'&&value(7)==='61','Absence, leave and overtime retain saved evidence');
    assert($('companyLogo').getAttribute('src').startsWith('data:image/png;base64,')&&!$('companyLogo').hidden,'Company logo must be embedded and visible');
    assert($('companyLogo').alt==='Example Logistics logo','Company logo has business-specific accessible text');
    assert(document.querySelectorAll('#locations .chart-row').length===2,'Location charts match captured locations');
    assert(document.querySelectorAll('#roles .chart-row').length===2,'Role charts match captured roles');
    assert(document.querySelectorAll('#shifts .chart-row').length===2,'Shift-start chart uses Jamaica times');
    assert($('summary').children.length===2,'Location/role summary matches chart groups');
    assert($('employees').children.length===6,'Exceptions omit attended-without-issues and approved leave');
    assert($('risks').textContent.includes('1 ended shift(s) without clock-out'),'Ended shifts with no clock-out are flagged');
    assert($('risks').textContent.includes('1 early departure(s)'),'Early-departure count uses recorded rule result');
    assert($('employees').textContent.includes('Worked-time validation pending'),'Short open shifts stay unconfirmed');
    assert(document.querySelectorAll('#employees .name-late').length===2,'Late names use amber styling with status labels');
    assert(document.querySelectorAll('#employees .name-absent').length===1,'Absent names use red styling with status labels');
    const kingston=[...document.querySelectorAll('#locations button')].find(el=>el.textContent.includes('Kingston'));
    kingston.click();
    assert($('location').value==='Kingston'&&value(0)==='50.0%'&&value(1)==='4','Location drill-down updates KPI denominator and percentage');
    assert($('summary').children.length===1&&$('summary').textContent.includes('Kingston'),'Chart drill-down filters summary table');
    assert(!$('employees').textContent.includes('Gray Example'),'Chart drill-down filters employee register');
    $('reset').click();
    change('role','Dispatch');
    assert(value(0)==='66.7%'&&value(1)==='3','Role filtering updates all metrics');
    assert(document.querySelectorAll('#locations .chart-row').length===1,'Role filtering updates charts');
    $('reset').click();
    change('shift','14:00');
    assert(value(1)==='1'&&value(0)==='0.0%'&&$('employees').textContent.includes('Flynn Example'),'Jamaica shift filtering preserves pending validation');
    assert(!$('risks').textContent.includes('1 ended shift(s) without clock-out'),'Open shifts do not count as ended missing-clock-out incidents');
    $('reset').click();
    change('status','approved_leave');
    assert(value(1)==='0'&&value(0)==='N/A'&&value(6)==='1','Leave-only view has unavailable rate, not zero percent');
    $('reset').click();
    const pending=[...document.querySelectorAll('#composition button')].find(el=>el.textContent.includes('Awaiting validation'));
    pending.click();
    assert(value(1)==='2'&&value(0)==='0.0%','Composition drill-down filters by mutually exclusive validation groups');
    [...document.querySelectorAll('#composition button')].find(el=>el.getAttribute('aria-pressed')==='true').click();
    assert(value(1)==='7','Clicking active composition restores unfiltered view');
    $('search').value='Gray';$('search').dispatchEvent(new Event('input'));
    assert(value(1)==='1'&&value(7)==='61'&&$('employees').textContent.includes('Gray Example'),'Search filters KPIs, charts and exception details');
    $('search').value='does-not-exist';$('search').dispatchEvent(new Event('input'));
    assert(value(0)==='N/A'&&value(1)==='0','Empty search is explicitly unavailable rather than a false attendance rate');
    assert($('locations').textContent.includes('No shifts')&&$('employees').textContent.includes('No employee exceptions'),'Empty chart and register states are explicit');
    $('reset').click();
    $('exceptionsOnly').checked=false;$('exceptionsOnly').dispatchEvent(new Event('change'));
    assert($('employees').children.length===8,'All-records mode includes leave and clean attended records');
    const sort=document.querySelector('[data-sort=name]');sort.click();
    assert(sort.closest('th').getAttribute('aria-sort')==='ascending','Employee sort exposes ascending order');
    const first=$('employees').firstChild.children[1].firstChild.textContent;
    sort.click();
    assert(sort.closest('th').getAttribute('aria-sort')==='descending'&&$('employees').firstChild.children[1].firstChild.textContent!==first,'Employee sort reverses actual rows');
    $('reset').click();
    assert($('exceptionsOnly').checked&&value(1)==='7','Reset restores default exception mode and all scope filters');
    assert($('printScope').textContent.includes('All locations'),'Print output records active filter scope');
    assert(!document.querySelector('script[src],link[href],img[src^="http"]'),'Report has no external assets');
    assert($('definitions').textContent.includes('four-hour'),'Existing four-hour absence rule remains explicit');
    assert($('reportError').hidden,'Production report completed without rendering errors');
    return {passed};
}
